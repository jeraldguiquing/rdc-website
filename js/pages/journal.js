    function updateFilterCounts() {
      var counts = { all: 0, mcnp: 0, isap: 0, admin: 0 };
      cards.forEach(function (card) {
        var jnl = card.dataset.journal || '';
        var disc = card.dataset.discipline || '';
        var text = (card.textContent || '').toLowerCase();
        var matchesDisc = (activeDiscipline === 'all') || (disc === activeDiscipline);
        var matchesSearch = !searchQuery || (text.indexOf(searchQuery) !== -1);

        if (matchesDisc && matchesSearch) {
          counts.all++;
          if (jnl && counts[jnl] !== undefined) counts[jnl]++;
        }
      });

      if (totalCountEl) totalCountEl.textContent = counts.all;
      if (mcnpCountEl) mcnpCountEl.textContent = counts.mcnp;
      if (isapCountEl) isapCountEl.textContent = counts.isap;
      if (adminCountEl) adminCountEl.textContent = counts.admin;
      if (quickCountEl) quickCountEl.textContent = counts.all;
    }

    function sortCards(list) {
      if (activeSort === 'downloads') {
        return list.slice().sort(function (a, b) {
          var da = parseInt(a.dataset.downloads || '0', 10);
          var db = parseInt(b.dataset.downloads || '0', 10);
          return db - da;
        });
      } else if (activeSort === 'title') {
        return list.slice().sort(function (a, b) {
          var ta = (a.dataset.title || '').toLowerCase();
          var tb = (b.dataset.title || '').toLowerCase();
          return ta.localeCompare(tb);
        });
      } else {
        return list.slice().sort(function (a, b) {
          return parseInt(a.dataset.originalIndex, 10) - parseInt(b.dataset.originalIndex, 10);
        });
      }
    }

    function filterArticles() {
      var sorted = sortCards(cards);
      var visible = 0;

      sorted.forEach(function (card) {
        if (gridEl) gridEl.appendChild(card);

        var jnl = card.dataset.journal || '';
        var disc = card.dataset.discipline || '';
        var text = (card.textContent || '').toLowerCase();

        var matchesJournal = (activeJournal === 'all') || (jnl === activeJournal);
        var matchesDisc = (activeDiscipline === 'all') || (disc === activeDiscipline);
        var matchesSearch = !searchQuery || (text.indexOf(searchQuery) !== -1);

        if (matchesJournal && matchesDisc && matchesSearch) {
          card.style.display = 'flex';
          visible++;
        } else {
          card.style.display = 'none';
        }
      });

      updateFilterCounts();
    }

